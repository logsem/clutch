(** * A group of prime order for the executable instances

    The quadratic residues modulo a safe prime [p = 2q + 1] form a cyclic
    subgroup of [Zpˣ] of prime order [q], generated by any square other
    than 1.  Elements are represented as in [valgroup_Zpx], by their
    residue; multiplication, inversion and equality are those of [Zpˣ].
    The index of an element is its discrete logarithm to the generator:
    [vg_of_int i = g^i] for [0 ≤ i < q], and [int_of_vg] searches.

    The authentication and oblivious-transfer results assume a group of
    prime order, which [Zpˣ] is not for [p > 3].  This instance is not
    proved to satisfy the class laws ([clutch_group]); it is meant for
    testing only. *)
From clutch.prob_eff_lang.probblaze Require Import syntax notation.
From clutch.prob_eff_lang.probblaze.examples Require Import valgroup valgroup_Zpx.
From clutch_exec Require Import zpx_ops.

Section qr.
  (** [p''' = p - 3] as in [valgroup_Zpx], the order [q], the generator. *)
  Variables (p''' q : nat) (gen : Z).
  #[local] Notation mult := (vmult_p p''').

  Definition qr_vg_of_int : val :=
    λ: "i", if: (#0 ≤ "i") && ("i" < #q) then SOME (vexp' vunit_z mult #gen "i") else NONE.

  Definition qr_int_of_vg : val :=
    λ: "x",
      (rec: "go" "i" :=
         if: #q ≤ "i" then #(-1)
         else if: vexp' vunit_z mult #gen "i" = "x" then "i" else "go" ("i" + #1)) #0.
End qr.
