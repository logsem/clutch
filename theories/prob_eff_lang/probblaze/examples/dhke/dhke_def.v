  #[local] Notation n := (S n'').

  Definition sample : expr := λ: <>, rand #n.
  Definition samplelbl α : expr := λ: <>, (rand(α) #n).

  Definition Send (e : expr) := InjL e.
  Definition Recv (e : expr) := InjR e.
  Definition SendV (v : val) := InjLV v.
  Definition RecvV (v : val) := InjRV v.
  Definition bob := InjLV #()%V.
  Definition alice := InjRV #()%V.

  Definition F_AUTH : val := λ: <>,
    let: "m1" := ref NONEV in
    let: "m2" := ref NONEV in
    λ: "f" "effs",  
      let, ("doLeakSend", "doLeakRecv") := "effs" in
      effect "send"
        effect "recv"
        let: "doSend" := (λ: "m", do: "send" "m") in  
        let: "doRecv" := (λ: "m", do: "recv" "m") in
        handle: handle: "f" ("doSend", "doRecv") with
    | effect "send" "message", rec "k" =>
        let, ("m", "dst") := "message" in
        match: "dst" with
          (* Alice *)
          InjL <> => match: !"m1" with (* Send only the first value. Discard all others.  *)
                       NONE => "m1" <- SOME "m";; ("doLeakSend" ("m", "dst"));; "k" #()%V
                     | SOME "x" => "k" #()%V 
                     end
        (* Bob *)
        | InjR <> => match: !"m2" with
                       NONE => "m2" <- SOME "m";; ("doLeakSend" ("m", "dst"));; "k" #()%V
                     | SOME "x" => "k" #()%V 
                     end
        end
    | return "y" => #()%V end with
(* Recv *)
| effect "recv" "from", rec "k" =>
    let: "r" := ("doLeakRecv" "from") in
    match: "r" with
      NONE => "k" NONEV
    | SOME "x" => match: "from" with
                    (* Alice *)
                    InjL <> => match: !"m2" with
                                 NONE => "k" NONEV
                               | SOME "m" => "k" (SOME "m")
                               end
                  (* Bob *)
                  | InjR <> => match: !"m1" with
                                 NONE => "k" NONEV
                               | SOME "m" => "k" (SOME "m")
                               end
                  end
    end
| return "y" => #()%V end.

  Definition DH_KE : val := λ: <>,
    let: "α" := alloc #n in
    let: "β" := alloc #n in
    let: "l1" := ref NONEV in
    let: "l2" := ref NONEV in

    λ: "f" "effs",
      let, ("doSend", "doRecv") := "effs" in
      
      effect "getKey"  
        let: "doGK" := (λ: "party", do: (EffName "getKey") "party") in
        handle: "f" "doGK" with
    | effect (EffName "getKey") "p", rec "k" =>
        match: "p" with
          (* Alice *)
          InjL <> =>
            (* Sample *)
            let: "a" :=
              (match: !"l1" with
                 NONE => let: "a" := (samplelbl "α" #()%V) in "l1" <- SOME "a";; "a"
               | SOME "a" => "a"
               end) in
            (* Compute gA *)
            let: "gA" := g^"a" in
            (* Send gA *)
            ("doSend" ("gA", bob));;
            (* Receive gB *)
            let: "r" := ("doRecv" bob) in
            match: "r" with
              NONE => "k" NONEV
            | SOME "gB" =>
                (* Compute key *)
                let: "key" := "gB"^"a" in
                "k" (SOME "key")
            end
        (* Bob *)
        | InjR <> =>
            let: "r" := ("doRecv" alice) in
            match: "r" with
              NONE => "k" NONE
            | SOME "gA" =>
                let: "b" :=
                  match: !"l2" with
                    NONE => let: "b" := (samplelbl "β" #()%V) in "l2" <- SOME "b";; "b"
                  | SOME "b" => "b"
                  end in
                let: "gB" := g^"b" in
                ("doSend" ("gB", alice));;

                let: "key" := "gA"^"b" in
                "k" (SOME "key")
            end
        end
    | return "y" => "y" end.

  (* The part of [DH_KE] after its setup, with the setup variables as
     parameters, so that the typing can be done on the core ([dhke_typing]). *)
  Definition dh_core (f effs α β l1 l2 : expr) : expr :=
    let, ("doSend", "doRecv") := effs in
    effect "getKey"
      let: "doGK" := (λ: "party", do: (EffName "getKey") "party") in
      handle: f "doGK" with
    | effect (EffName "getKey") "p", rec "k" =>
        match: "p" with
          InjL <> =>
            let: "a" :=
              (match: !l1 with
                 NONE => let: "a" := (samplelbl α #()%V) in l1 <- SOME "a";; "a"
               | SOME "a" => "a"
               end) in
            let: "gA" := g^"a" in
            ("doSend" ("gA", bob));;
            let: "r" := ("doRecv" bob) in
            match: "r" with
              NONE => "k" NONEV
            | SOME "gB" =>
                let: "key" := "gB"^"a" in
                "k" (SOME "key")
            end
        | InjR <> =>
            let: "r" := ("doRecv" alice) in
            match: "r" with
              NONE => "k" NONE
            | SOME "gA" =>
                let: "b" :=
                  match: !l2 with
                    NONE => let: "b" := (samplelbl β #()%V) in l2 <- SOME "b";; "b"
                  | SOME "b" => "b"
                  end in
                let: "gB" := g^"b" in
                ("doSend" ("gB", alice));;
                let: "key" := "gA"^"b" in
                "k" (SOME "key")
            end
        end
    | return "y" => "y" end.

  Lemma DH_KE_core_eq :
    DH_KE =
      (λ: <>,
       let: "α" := alloc #n in
       let: "β" := alloc #n in
       let: "l1" := ref NONEV in
       let: "l2" := ref NONEV in
       λ: "f" "effs", dh_core "f" "effs" "α" "β" "l1" "l2")%V.
  Proof. reflexivity. Qed.

  (* [DH_KE] without tapes: [rand #n] is [rand(#()) #n], so binding the tape
     variables to [#()] makes the core sample directly. *)
  Definition DH_KE_tapeless : val := λ: <>,
    let: "α" := #()%V in
    let: "β" := #()%V in
    let: "l1" := ref NONEV in
    let: "l2" := ref NONEV in
    λ: "f" "effs", dh_core "f" "effs" "α" "β" "l1" "l2".

 Definition DH_SIM : val := λ: <>,
   let: "α" := alloc #n in
   let: "β" := alloc #n in
   let: "l1" := ref NONEV in
   let: "l2" := ref NONEV in
   λ: "f" "effs",
     let, ("doSend", "doRecv") := "effs" in
     
     effect "leakSend"
       effect "leakRecv"
       let: "doLeakSend" := (λ: "m", do: "leakSend" "m") in
       let: "doLeakRecv" := (λ: "m", do: "leakRecv" "m") in
       handle: handle: "f" ("doLeakSend", "doLeakRecv") with
   | effect "leakSend" "dst", rec "k" =>
       match: "dst" with
         InjL <> => let: "c" := 
                      (match: !"l1" with
                         NONE => let: "c" := (samplelbl "α" #()%V) in "l1" <- SOME "c";; "c"
                       | SOME "c" => "c"
                       end) in
                    let: "gC" := g^"c" in
                    "doSend" ("gC",bob);;
                    "k" #()%V
       | InjR <> => let: "c" :=
                      (match: !"l2" with
                         NONE => let: "c" := (samplelbl "β" #()%V) in "l2" <- SOME "c";; "c"
                       | SOME "c" => "c"
                       end) in
                    let: "gC" := g^"c" in
                    "doSend" ("gC", alice);;
                    "k" #()%V
       end
   | return "y" => "y" end with
| effect "leakRecv" "from", rec "k" => 
    let: "r" := "doRecv" "from" in
    match: "r" with
      NONE => "k" NONE
    | SOME "x" => "k" (SOME #()%V)
    end
| return "y" => "y" end.

  
   (* The ideal key exchange with an eagerly sampled key.  Not used by the
      DHKE proofs, which use the lazy [F_KE_lazy_alice]; kept in the common
      shape: a factory whose session allocates its state before taking the
      client. *)
   Definition F_KE : val :=
     λ: <>,
       (* Magically share a presampled key *)
       let: "c" := (sample #()%V) in
       let: "key" := g^"c" in
       λ: "f" "effs",
       let, ("doLeakSend", "doLeakRecv") := "effs" in
       effect "getKey"
         let: "doGK" := (λ: "party", do: (EffName "getKey") "party") in
         handle: "f" "doGK" with
     | effect (EffName "getKey") "p", rec "k" as multi =>
         match: "p" with
           (* Alice *)
           InjL <> =>
             (* Leak a send *)
             ("doLeakSend" bob);;
             (* Receive a dummy value *)
             let: "r" := ("doLeakRecv" bob) in
             match: "r" with
               NONE => "k" NONEV
             | SOME "w" => "k" (SOME "key")
             end
         (* Bob  *)
         | InjR <> =>
             let: "r" := ("doLeakRecv" alice) in
             match: "r" with
               NONE => "k" NONEV
             | SOME "w" => 
                 ("doLeakSend" alice);;
                 "k" (SOME "key")
             end
         end
     | return "y" => "y" end.


   Definition F_KE_lazy_alice : val := λ: <>,
       let: "γ" := alloc #n in
       let: "lc" := ref NONEV in
       let: "sample_or_load" :=
         λ:<>, match: !"lc" with
           | NONE =>
               let: "c" := (samplelbl "γ" #()%V) in
               "lc" <- SOME "c" ;;
               "c"
           | SOME "c" => "c"
           end
       in

     λ: "f" "effs",
       let, ("doLeakSend", "doLeakRecv") := "effs" in
       (* Magically share a lazily sampled key *)

       effect "getKey"
         let: "doGK" := (λ: "party", do: (EffName "getKey") "party") in
     handle: "f" "doGK" with
     | effect (EffName "getKey") "p", rec "k" =>
         match: "p" with
           (* Alice *)
           InjL <> =>
             let: "c" := "sample_or_load" #()%V in
             let: "key" := g^"c" in
             (* Leak a send *)
             ("doLeakSend" bob);;
             (* Receive a dummy value *)
             let: "r" := ("doLeakRecv" bob) in
             match: "r" with
               NONE => "k" NONEV
             | SOME "w" =>
                 "k" (SOME "key")
             end
         (* Bob  *)
         | InjR <> =>
             let: "r" := ("doLeakRecv" alice) in
             match: "r" with
               NONE => "k" NONEV
             | SOME "w" =>
                 ("doLeakSend" alice);;
                 match: !"lc" with
                 | NONE => "k" NONEV
                 | SOME "c" =>
                     let: "key" := g^"c" in
                     "k" (SOME "key")
                 end
             end
         end
     | return "y" => "y" end.

