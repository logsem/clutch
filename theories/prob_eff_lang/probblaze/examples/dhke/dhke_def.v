  Definition DH_real : val :=
    λ: <>,
    let: "a" := sample #()%V in
    let: "b" := sample #()%V in
    (g^"a", g^"b", g^("a"*"b")).

  Definition DH_rand : val :=
    λ: <>,
    let: "a" := sample #()%V in
    let: "b" := sample #()%V in
    let: "c" := sample #()%V in
    ( g^"a", g^"b", g^"c").




    
  (* The systems are factories (uc/DESIGN.md): a call allocates the state of
     a fresh session and returns it.  [C_lazy d] is the reduction for a DDH
     oracle [d]; [C_lazy_sess] is its session, parametrised by the oracle.
     [AsRecV] lets the pure-step tactics call a factory without unfolding
     it. *)
  Definition C_lazy : val := λ: "DH", λ: <>, C_lazy_sess "DH".
  Definition C_DH_real : val := λ: <>, C_lazy_sess DH_real.
  Definition C_DH_rand : val := λ: <>, C_lazy_sess DH_rand.
