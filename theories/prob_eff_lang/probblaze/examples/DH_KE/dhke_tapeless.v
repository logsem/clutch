  (* A read from a tape that only the left side owns, and that stays empty,
     against an untaped [rand] on the right: couple the right [rand] with a
     presampling onto the tape, then read it back. *)
  Lemma sem_typed_rand_tape_l N α Γ ρ :
    na_invP N (α ↪N (n; [])) -∗
    sem_typed Γ (rand(#lbl:α) #n) (rand #n) ρ ℕ Γ.
  Proof.
    iIntros "#Hinv !# %vs HΓ /=".
    iApply (brel_na_inv _ _ N); [done|]. iFrame "Hinv".
    iIntros "(>Hα & Hclose)".
    iDestruct (tapeN_to_empty with "Hα") as "Hα".
    iApply (brel_couple_TU _ _ _ []); [done|]. iFrame "Hα". iIntros (k) "Hα /=".
    iAssert (α ↪N (n; [fin_to_nat k]))%I with "[Hα]" as "Hα".
    { iExists [k]. by iFrame. }
    brel_rand_l.
    iApply brel_na_close. iFrame "Hclose Hα".
    iApply brel_value. iIntros "$ !>". iFrame. by iExists _.
  Qed.

  (* The mirror image: the tape is owned by the right side only. *)
  Lemma sem_typed_rand_tape_r N α Γ ρ :
    na_invP N (α ↪ₛN (n; [])) -∗
    sem_typed Γ (rand #n) (rand(#lbl:α) #n) ρ ℕ Γ.
  Proof.
    iIntros "#Hinv !# %vs HΓ /=".
    iApply (brel_na_inv _ _ N); [done|]. iFrame "Hinv".
    iIntros "(>Hα & Hclose)".
    iApply (brel_couple_UT _ _ (λ k : nat, k) []); [done|]. iFrame "Hα".
    iIntros "!>" (k) "% Hα /=".
    brel_rand_r.
    iApply brel_na_close. iFrame "Hclose Hα".
    iApply brel_value. iIntros "$ !>". iFrame. by iExists _.
  Qed.

  (* [sem_typed_vexp] with a 𝔾-typed base instead of a constant one. *)
  Lemma sem_typed_vexp_gen Γ1 Γ2 Γ3 e1 e1' e2 e2' ρ :
    ⊢ sem_typed Γ1 e2 e2' ρ ℕ Γ2 -∗ sem_typed Γ2 e1 e1' ρ 𝔾 Γ3 -∗
      sem_typed Γ1 (vexp e1 e2) (vexp e1' e2') ρ 𝔾 Γ3.
  Proof using G vgg.
    iIntros "#He2 #He1 !# %γ HΓ1 /=".
    iApply (brel_bind [AppRCtx _] [AppRCtx _]); [iApply traversable_to_iThy|iApply to_iThy_le_refl|].
    iApply (brel_wand with "[HΓ1]"); first by iApply "He2".
    iIntros "!# % % ((%p & -> & ->) & HΓ2) /=".
    iApply (brel_bind [AppLCtx _; AppRCtx _] [AppLCtx _; AppRCtx _]); [iApply traversable_to_iThy|iApply to_iThy_le_refl|].
    iApply (brel_wand with "[HΓ2]"); first by iApply "He1".
    iIntros "!# % % ((%b & -> & ->) & HΓ3) /=".
    iApply (brel_exp_l []). iApply (brel_exp_r []).
    iApply brel_value. iIntros "$ !>". iFrame. by iExists _.
  Qed.

  (* Go back from a [brel] goal to a typing judgement for closed terms. *)
  Lemma sem_typed_brel e1 e2 ρ τ vs :
    sem_typed [] e1 e2 ρ τ [] ⊢
    BREL e1 ≤ e2 <|iLblSig_to_iLblThy ρ|> {{ λ v1 v2, τ v1 v2 ∗ [] ⊨ₑ vs }}.
  Proof.
    rewrite /sem_typed /tc_opaque. iIntros "#He".
    iSpecialize ("He" $! ∅ with "[]"); first by rewrite env_sem_typed_empty.
    rewrite !fmap_empty !subst_map_empty.
    iApply (brel_wand with "He"). iIntros "!# % % [$ _]".
  Qed.

  (* The tapes of [DH_KE] are a proof device: [DH_KE] refines the version
     that samples directly. *)
  Lemma DH_KE_DH_KE_tapeless :
    ⊢ sem_typed [] DH_KE DH_KE_tapeless ⊥ (τ__F chan gk) [].
  Proof using All.
    iIntros (vs) "!# _".
    rewrite !subst_map_is_closed_empty; [|is_closed|is_closed].
    rewrite /DH_KE /DH_KE_tapeless /sample.
    (* The tapes exist only on the left; they stay empty forever. *)
    brel_alloctape_l α as "Hα". brel_pures_l.
    brel_alloctape_l β as "Hβ". brel_pures_l.
    rewrite Nat2Z.id.
    iApply (brel_na_alloc (α ↪N (n; [])) alphaN). iFrame "Hα". iIntros "#Hα".
    iApply (brel_na_alloc (β ↪N (n; [])) betaN). iFrame "Hβ". iIntros "#Hβ".
    (* From here on both sides have the same shape: type them, with
       [sem_typed_rand_tape_l] for the two reads. *)
    iApply (sem_typed_brel _ _ ⊥ (τ__F chan gk) vs).
    iApplyT sem_typed_let; first (iApplyT sem_typed_alloc_cpy; iApplyT (sem_typed_none ℕ)).
    iApplyT sem_typed_let; first (iApplyT sem_typed_alloc_cpy; iApplyT (sem_typed_none ℕ)).
    iApply sem_typed_sub_nil. iApply (sem_typed_oval _ [_; _]). iApply sem_typed_RLam. iIntros (θ).
    iApplyT sem_oval_typed_afun.
    iApply (sem_typed_oval _ [_; _; _]). iApply sem_typed_RLam. iIntros (θ₂).
    iApplyT sem_oval_typed_afun. simpl.
    iApplyT sem_typed_pair_elim; first typed_var.
    iApply sem_typed_effect_gen. iIntros (gk1 gk2). simpl.
    iApplyT sem_typed_let.
    { iApply sem_typed_sub_nil. iApply (sem_typed_oval _ []).
      iApplyT sem_oval_typed_ufun.
      iApply (sem_typed_do_const OS ⟨⟩%R (gk1, gk2) (𝟙 + 𝟙)%T (Option 𝔾)%T).
      iApply sem_typed_sub_nil. iApply sem_typed_var. }
    iApplyT sem_typed_sub_env_final; first iApply env_le_nil.
    iApplyT (sem_typed_sub_env _ ([("doGK", _); ("f", _)]
                                    ++ [("l1", _); ("l2", _); ("doSend", _); ("doRecv", _)])).
    { simpl. env_solve. }
    iApplyT (sem_typed_deep_handler_OS (gk1, gk2) (λ _, 𝟙 + 𝟙)%T (λ _, Option 𝔾)%T).
    - (* The client call [f doGK], at [¡θ₁ ∪ θ ≤ θ₁ ∪ θ]. *)
      iApplyT sem_typed_app_fun_nil.
      2: typed_var.
      2: { iApplyT sem_typed_sub_ty; last typed_var. iApply ty_le_row_forall_inst. }
      iApply row_le_trans; first iApplyT row_le_union'.
      + iApply row_le_mfbang_elim.
      + iApply row_le_refl.
      + row_le_submseteq.
    - iIntros (?). simpl.
      iApplyT (sem_typed_match_split [] []).
      + typed_var.
      + iApply env_le_refl.
      + (* Alice: draw (or load) [a], send [g^a], receive [gB]. *)
        iApplyT sem_typed_let.
        { iApplyT (sem_typed_match_split [] []).
          - iApplyT sem_typed_load_cpy. typed_var_copy.
          - iApply env_le_refl.
          - iApplyT sem_typed_let.
            { iApplyT sem_typed_let; first iApplyT sem_typed_unit'.
              iApply (sem_typed_rand_tape_l with "Hα"). }
            iApplyT sem_typed_seq.
            { iApplyT sem_typed_store_cpy_gen.
              2: { iApplyT sem_typed_injr. typed_var_copy. }
              typed_var_copy. }
            typed_var.
          - iApply env_le_refl.
          - iApply env_le_refl.
          - typed_var.
          - iApply env_le_refl. }
        iApplyT sem_typed_let; first (iApplyT sem_typed_vexp; typed_var_copy).
        iApplyT sem_typed_seq.
        { iApplyT sem_typed_app_fun_nil; [row_le_submseteq|iApplyT sem_typed_pair; [iApply (sem_typed_party true)|typed_var]|typed_leak_fun]. }
        iApplyT sem_typed_let.
        { iApplyT sem_typed_app_fun_nil; [row_le_submseteq|iApply (sem_typed_party true)|typed_leak_fun]. }
        iApplyT (sem_typed_match_split [] []).
        * typed_var.
        * iApply env_le_refl.
        * iApplyT sem_typed_sub_env; first iApply env_le_weaken.
          iApplyT sem_typed_app_fun_nil; [iApply row_le_refl|iApplyT sem_typed_none|typed_cont].
        * iApply env_le_refl.
        * iApply env_le_refl.
        * iApplyT sem_typed_let; first (iApplyT sem_typed_vexp_gen; typed_var).
          iApplyT sem_typed_app_fun_nil; [iApply row_le_refl|iApplyT sem_typed_injr; typed_var|typed_cont].
        * iApply env_le_refl.
      + iApply env_le_refl.
      + iApply env_le_refl.
      + (* Bob: receive [gA], draw (or load) [b], send [g^b]. *)
        iApplyT sem_typed_let.
        { iApplyT sem_typed_app_fun_nil; [row_le_submseteq|iApply (sem_typed_party false)|typed_leak_fun]. }
        iApplyT (sem_typed_match_split [] []).
        * typed_var.
        * iApply env_le_refl.
        * iApplyT sem_typed_app_fun_nil; [iApply row_le_refl|iApplyT sem_typed_injl; iApplyT sem_typed_unit'|typed_cont].
        * iApply env_le_refl.
        * iApply env_le_refl.
        * iApplyT sem_typed_let.
          { iApplyT (sem_typed_match_split [] []).
            - iApplyT sem_typed_load_cpy. typed_var_copy.
            - iApply env_le_refl.
            - iApplyT sem_typed_let.
              { iApplyT sem_typed_let; first iApplyT sem_typed_unit'.
                iApply (sem_typed_rand_tape_l with "Hβ"). }
              iApplyT sem_typed_seq.
              { iApplyT sem_typed_store_cpy_gen.
                2: { iApplyT sem_typed_injr. typed_var_copy. }
                typed_var_copy. }
              typed_var.
            - iApply env_le_refl.
            - iApply env_le_refl.
            - typed_var.
            - iApply env_le_refl. }
          iApplyT sem_typed_let; first (iApplyT sem_typed_vexp; typed_var_copy).
          iApplyT sem_typed_seq.
          { iApplyT sem_typed_app_fun_nil; [row_le_submseteq|iApplyT sem_typed_pair; [iApply (sem_typed_party false)|typed_var]|typed_leak_fun]. }
          iApplyT sem_typed_let; first (iApplyT sem_typed_vexp_gen; typed_var).
          iApplyT sem_typed_app_fun_nil; [iApply row_le_refl|iApplyT sem_typed_injr; typed_var|typed_cont].
        * iApply env_le_refl.
      + iApply env_le_refl.
    - typed_var.
      Unshelve. all: solve_typed_side.
  Qed.

